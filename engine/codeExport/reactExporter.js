/**
 * Professional React Animation Component Exporter for MotionLab
 * Generates an idiomatic, typed or JSX React component with GSAP lifecycle hooks,
 * dependency declarations, and copy-paste ready documentation.
 */

export function exportProjectToReact(project, layers = [], keyframes = []) {
  const width = Number(project?.width || 1920);
  const height = Number(project?.height || 1080);
  const duration = Number(project?.duration || 5.0);
  const bgColor = project?.backgroundColor || "#0a0a0f";
  const rawTitle = project?.name || "MotionLabAnimation";
  const compName = rawTitle.replace(/[^a-zA-Z0-9]/g, "") || "MotionLabBanner";

  let layerElements = "";
  let timelineCode = "";

  for (const layer of layers) {
    if (layer.visible === false || layer.type === "audio") continue;

    const refName = `layerRef_${layer.id.replace(/[^a-zA-Z0-9]/g, "_")}`;
    const layerKfs = keyframes.filter((k) => k.objectId === layer.id);

    const baseX = Number(layer.x ?? 0);
    const baseY = Number(layer.y ?? 0);
    const baseW = Number(layer.width ?? 100);
    const baseH = Number(layer.height ?? 100);
    const baseRot = Number(layer.rotation ?? 0);
    const baseOp = Number(layer.opacity ?? 1);
    const baseFill = layer.fill || "#6366f1";

    let styleObj = `position: "absolute", top: 0, left: 0, width: ${baseW}, height: ${baseH}, backgroundColor: "${baseFill}", transform: "translate(${baseX}px, ${baseY}px) rotate(${baseRot}deg)", opacity: ${baseOp}`;
    if (layer.type === "circle") {
      styleObj = `position: "absolute", top: 0, left: 0, width: ${baseW}, height: ${baseW}, borderRadius: "50%", backgroundColor: "${baseFill}", transform: "translate(${baseX}px, ${baseY}px) rotate(${baseRot}deg)", opacity: ${baseOp}`;
    } else if (layer.type === "text") {
      styleObj = `position: "absolute", top: 0, left: 0, color: "${baseFill}", fontSize: ${layer.fontSize || 48}, fontWeight: "${layer.fontWeight || "bold"}", fontFamily: "${layer.fontFamily || "Inter"}, sans-serif", transform: "translate(${baseX}px, ${baseY}px) rotate(${baseRot}deg)", opacity: ${baseOp}, whiteSpace: "nowrap", userSelect: "none"`;
    }

    const textContent = layer.type === "text" ? layer.text || "" : "";
    layerElements += `        {/* Layer: ${layer.name} */}\n        <div data-motionlab-layer="${layer.id}" className="motionlab-node" style={{ ${styleObj} }}>\n          ${textContent}\n        </div>\n`;

    if (layerKfs.length > 0) {
      timelineCode += `    // Tween for ${layer.name}\n`;
      const times = Array.from(new Set(layerKfs.map((k) => k.time))).sort((a, b) => a - b);
      let prevTime = 0;

      for (const t of times) {
        const span = Math.max(0.01, t - prevTime);
        const matchX = layerKfs.find((k) => k.property === "x" && k.time === t);
        const matchY = layerKfs.find((k) => k.property === "y" && k.time === t);
        const matchRot = layerKfs.find((k) => k.property === "rotation" && k.time === t);
        const matchOp = layerKfs.find((k) => k.property === "opacity" && k.time === t);

        const props = [];
        if (matchX) props.push(`x: ${matchX.value}`);
        if (matchY) props.push(`y: ${matchY.value}`);
        if (matchRot) props.push(`rotation: ${matchRot.value}`);
        if (matchOp) props.push(`opacity: ${matchOp.value}`);

        if (props.length > 0) {
          timelineCode += `    tl.to('[data-motionlab-layer="${layer.id}"]', { duration: ${span.toFixed(2)}, ${props.join(", ")}, ease: "power2.inOut" }, ${prevTime.toFixed(2)});\n`;
        }
        prevTime = t;
      }
    }
  }

  const reactCode = `"use client";

import React, { useRef, useEffect } from "react";
import gsap from "gsap";

/**
 * ${compName} - React Animation Component
 * Generated by MotionLab Stage 11 (Advanced Code Export)
 * 
 * 📦 Installation:
 *   npm install gsap
 * 
 * 💡 Usage Example:
 *   import ${compName} from "./${compName}";
 *   
 *   export default function Page() {
 *     return <${compName} autoPlay={true} loop={true} scale={1.0} />;
 *   }
 */
export default function ${compName}({
  autoPlay = true,
  loop = true,
  scale = 1.0,
  className = "",
  style = {},
  onComplete = null,
}) {
  const containerRef = useRef(null);
  const timelineRef = useRef(null);

  useEffect(() => {
    const ctx = gsap.context(() => {
      const tl = gsap.timeline({
        paused: !autoPlay,
        repeat: loop ? -1 : 0,
        onComplete: () => {
          if (onComplete) onComplete();
        },
      });

${timelineCode}
      timelineRef.current = tl;
    }, containerRef);

    return () => ctx.revert(); // Clean memory leak prevention
  }, [autoPlay, loop, onComplete]);

  return (
    <div
      ref={containerRef}
      className={\`motionlab-animation-wrapper relative overflow-hidden \${className}\`}
      style={{
        width: ${width} * scale,
        height: ${height} * scale,
        backgroundColor: "${bgColor}",
        transformOrigin: "top left",
        ...style,
      }}
    >
      <div
        className="motionlab-stage absolute inset-0"
        style={{
          width: ${width},
          height: ${height},
          transform: \`scale(\${scale})\`,
          transformOrigin: "top left",
        }}
      >
${layerElements}      </div>
    </div>
  );
}
`;

  return {
    code: reactCode,
    filename: `${compName}.jsx`,
    mimeType: "text/javascript",
  };
}
